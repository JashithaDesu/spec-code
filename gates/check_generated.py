"""Gate 2: src/generated/ is exactly what the generator produces from the current spec.

Fails if generated code was edited by hand, or if the spec changed without regenerating.
This is what makes "the spec is the source of truth" enforceable."""
import difflib
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from generator.generate import generate  # noqa: E402

GENERATED = ROOT / "src" / "generated"


def main():
    with tempfile.TemporaryDirectory() as tmp:
        expected_files = generate(tmp)
        actual_files = sorted(p.name for p in GENERATED.glob("*.py"))
        problems = []
        for extra in sorted(set(actual_files) - set(expected_files)):
            problems.append(f"unexpected file in src/generated: {extra}")
        for name in expected_files:
            expected = (Path(tmp) / name).read_text(encoding="utf-8")
            actual_path = GENERATED / name
            actual = actual_path.read_text(encoding="utf-8") if actual_path.exists() else ""
            if expected != actual:
                diff = difflib.unified_diff(expected.splitlines(), actual.splitlines(),
                                            f"expected/{name}", f"src/generated/{name}", lineterm="", n=1)
                problems.append(f"{name} differs from the generator output:\n" + "\n".join(list(diff)[:20]))
    for problem in problems:
        print(problem)
    if problems:
        print("check_generated: FAILED - run `python generator/generate.py` and never edit src/generated by hand")
        return 1
    print("check_generated: passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
